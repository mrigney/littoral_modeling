def write_frame_metadata(mesh, path, extra: dict | None = None) -> Path:
    """Sidecar JSON: everything needed to regenerate this exact frame.

    Cookbook 6.6 wants provenance per frame, and it is right about why -- when a
    signature question surfaces months later, the first thing anyone asks is
    what wind, what seed, what code produced that image.
    """
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)

    doc = dict(mesh.meta)
    doc.update({
        "git_sha": _git_sha(),
        "written_utc": f"{datetime.now(timezone.utc):%Y-%m-%d %H:%M:%S}",
        "n_vertices": mesh.n_vertices,
        "n_faces": mesh.n_faces,
        "channels": {
            name: {
                "min": float(np.min(arr)), "max": float(np.max(arr)),
                "mean": float(np.mean(arr)),
            } for name, arr in sorted(mesh.channels.items())
        },
    })
    if extra:
        doc.update(extra)
    path.write_text(json.dumps(doc, indent=2) + "\n", encoding="utf-8")
    return path


def export_frame(mesh, directory, stem: str = "water", *,
                 obj: bool = False, quiet: bool = False) -> dict:
    """Write ``<stem>.ply`` plus its metadata, and optionally an OBJ.

    Returns the paths written.
    """
    directory = Path(directory)
    out = {"ply": write_ply(mesh, directory / f"{stem}.ply"),
           "json": write_frame_metadata(mesh, directory / f"{stem}.json")}
    if obj:
        out["obj"] = write_obj(mesh, directory / f"{stem}.obj", quiet=quiet)
    return out


