def write_obj(mesh, path, *, quiet: bool = False) -> Path:
    """Write a Wavefront OBJ. **Lossy** -- geometry and normals only.

    Every per-vertex channel is discarded, because OBJ has nowhere to put them.
    Use this to look at the mesh; use :func:`write_ply` for anything that feeds
    a renderer.
    """
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)

    dropped = sorted(mesh.channels)
    if dropped and not quiet:
        print(f"    note: OBJ cannot carry per-vertex channels; dropping "
              f"{', '.join(dropped)}. Use the PLY for rendering.")

    v = np.asarray(mesh.vertices, dtype=np.float64)
    n = np.asarray(mesh.normals, dtype=np.float64)
    f = np.asarray(mesh.faces, dtype=np.int64) + 1          # OBJ is 1-based

    with path.open("w", encoding="ascii", newline="\n") as fh:
        fh.write(f"# pywave water mesh, scene {mesh.meta.get('scene', 'unnamed')}, "
                 f"t = {mesh.meta.get('t', 0.0)} s\n")
        fh.write(f"# {mesh.n_vertices} vertices, {mesh.n_faces} faces, "
                 f"post spacing {mesh.meta.get('mesh_dx', '?')} m\n")
        if dropped:
            fh.write(f"# per-vertex channels NOT representable in OBJ: "
                     f"{', '.join(dropped)} -- see the PLY\n")
        np.savetxt(fh, v, fmt="v %.6f %.6f %.6f")
        np.savetxt(fh, n, fmt="vn %.6f %.6f %.6f")
        np.savetxt(fh, np.stack([f[:, 0], f[:, 0], f[:, 1], f[:, 1],
                                 f[:, 2], f[:, 2]], axis=1),
                   fmt="f %d//%d %d//%d %d//%d")
    return path


