def write_ply(mesh, path, *, channels: bool = True) -> Path:
    """Write a binary little-endian PLY with the per-vertex channels.

    Vertex properties are, in order: ``x y z nx ny nz`` then every channel in
    ``mesh.channels``, all float32. Faces are written with a ``uchar`` count and
    ``int`` indices, the convention every PLY reader expects.
    """
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)

    names = ["x", "y", "z", "nx", "ny", "nz"]
    cols = [mesh.vertices[:, 0], mesh.vertices[:, 1], mesh.vertices[:, 2],
            mesh.normals[:, 0], mesh.normals[:, 1], mesh.normals[:, 2]]
    if channels:
        for name in sorted(mesh.channels):
            names.append(name)
            cols.append(mesh.channels[name])

    vertex_dtype = np.dtype([(n, "<f4") for n in names])
    verts = np.empty(mesh.n_vertices, dtype=vertex_dtype)
    for n, c in zip(names, cols):
        verts[n] = np.asarray(c, dtype=np.float32)

    face_dtype = np.dtype([("n", "u1"), ("v", "<i4", (3,))])
    faces = np.empty(mesh.n_faces, dtype=face_dtype)
    faces["n"] = 3
    faces["v"] = mesh.faces.astype(np.int32)

    header = ["ply", "format binary_little_endian 1.0",
              f"comment generated by pywave at t = {mesh.meta.get('t', 0.0)} s",
              f"comment scene {mesh.meta.get('scene', 'unnamed')} "
              f"seed {mesh.meta.get('seed', '?')} "
              f"mesh_dx {mesh.meta.get('mesh_dx', '?')} m",
              f"element vertex {mesh.n_vertices}"]
    header += [f"property float {n}" for n in names]
    header += [f"element face {mesh.n_faces}",
               "property list uchar int vertex_indices", "end_header"]

    with path.open("wb") as fh:
        fh.write(("\n".join(header) + "\n").encode("ascii"))
        fh.write(verts.tobytes())
        fh.write(faces.tobytes())
    return path


def read_ply(path):
    """Minimal binary-PLY reader, for round-tripping our own output.

    Deliberately narrow: it handles the files :func:`write_ply` produces and
    nothing else. Its job is to let a test assert that the custom properties
    survive a write/read cycle -- the five-minute check cookbook 6.6 asks for
    before betting Phase 7 on it -- not to be a general PLY parser.
    """
    path = Path(path)
    with path.open("rb") as fh:
        if fh.readline().strip() != b"ply":
            raise ValueError(f"{path} is not a PLY file")
        fmt = fh.readline().strip()
        if fmt != b"format binary_little_endian 1.0":
            raise ValueError(f"unsupported PLY format: {fmt!r}")

        names, n_vertex, n_face, element = [], 0, 0, None
        while True:
            line = fh.readline()
            if not line:
                raise ValueError("unexpected end of PLY header")
            parts = line.split()
            if parts[0] == b"end_header":
                break
            if parts[0] == b"element":
                element = parts[1]
                if element == b"vertex":
                    n_vertex = int(parts[2])
                elif element == b"face":
                    n_face = int(parts[2])
            elif parts[0] == b"property" and element == b"vertex":
                if parts[1] != b"float":
                    raise ValueError(f"unsupported vertex property type {parts[1]!r}")
                names.append(parts[2].decode("ascii"))

        verts = np.frombuffer(fh.read(n_vertex * 4 * len(names)),
                              dtype=np.dtype([(n, "<f4") for n in names]))
        faces = np.frombuffer(fh.read(n_face * (1 + 12)),
                              dtype=np.dtype([("n", "u1"), ("v", "<i4", (3,))]))

    data = {n: np.array(verts[n]) for n in names}
    return data, np.array(faces["v"])


